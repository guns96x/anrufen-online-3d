--------------------技能常量总索引表------------------------
TABLE_SKILL_CONST = {}

function get_skill_const( nSN, nLv, strId )
	--获取技能常量
	
	if TABLE_SKILL_CONST[nSN] == nil then
		return 0
	elseif TABLE_SKILL_CONST[nSN][strId] == nil then
		return 0
	elseif TABLE_SKILL_CONST[nSN][strId][nLv] == nil then
		if nLv > table.getn(TABLE_SKILL_CONST[nSN][strId]) then
			return TABLE_SKILL_CONST[nSN][strId][table.getn(TABLE_SKILL_CONST[nSN][strId])]
		elseif nLv < 1 then
			return TABLE_SKILL_CONST[nSN][strId][1]
		end
		return 0
	else 
		return TABLE_SKILL_CONST[nSN][strId][nLv]
	end
end
